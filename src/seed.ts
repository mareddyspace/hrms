/** The date itself, or the next Monday when it falls on a weekend. */
function nextWorkday(iso: string): string {
  const day = parseISODate(iso).getDay();
  return day === 6 ? addDaysISO(iso, 2) : day === 0 ? addDaysISO(iso, 1) : iso;
}

